import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (path) => readFileSync(join(root, path), 'utf8');

function minify(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s+/g, ' ')
    .replace(/\s*([{}:;,>+~])\s*/g, '$1')
    .trim();
}

function extractMedia(css, query) {
  const marker = `@media ${query}`;
  const start = css.indexOf(marker);
  if (start < 0) return '';
  let depth = 0;
  let i = start;
  for (; i < css.length; i++) {
    if (css[i] === '{') depth++;
    if (css[i] === '}') {
      depth--;
      if (depth === 0) {
        i++;
        break;
      }
    }
  }
  return css.slice(start, i);
}

function extractPrefix(css, startNeedle, endNeedle) {
  const start = css.indexOf(startNeedle);
  if (start < 0) throw new Error(`Missing CSS marker: ${startNeedle}`);
  const end = css.indexOf(endNeedle, start + startNeedle.length);
  if (end < 0) throw new Error(`Missing CSS end marker: ${endNeedle}`);
  return css.slice(start, end);
}

const hero = read('src/public/hero.css');
const publicCss = read('src/public/public.css');
const shell = read('src/public/public-critical-shell.css');
const framed = read('src/components/FramedCover.css');

const baseHero = extractPrefix(hero, '.public-site .home-hero {', '@media');
const parts = [
  shell,
  framed,
  baseHero,
  extractMedia(hero, '(max-width: 760px)'),
  extractMedia(hero, '(max-width: 480px)'),
  extractMedia(publicCss, '(max-width: 760px)'),
  extractMedia(publicCss, '(max-width: 480px)'),
];

const generated = minify(parts.join('\n'));
const output = `/* Generated by scripts/generate-public-critical.mjs; do not edit. */\nexport default ${JSON.stringify(generated)};\n`;
const target = 'src/public/public-critical.generated.ts';
if (process.argv.includes('--check')) {
  if (read(target) !== output) {
    console.error(`${target} is stale; run npm run generate:critical`);
    process.exit(1);
  }
  console.log(`${target} is up to date (${generated.length} bytes minified)`);
} else {
  writeFileSync(join(root, target), output);
  console.log(`Wrote ${target} (${generated.length} bytes minified)`);
}
